//! An 8x8 bitmap font for Latin and Cyrillic.
//!
//! One byte per row, the most significant bit is the leftmost pixel. The
//! kernel owns its glyphs: after ExitBootServices there is no firmware console
//! left, so text on the framebuffer has to come from somewhere — and a system
//! that answers in Russian has to be able to draw Russian.

pub const glyph_width = 8;
pub const glyph_height = 8;

pub const Glyph = [glyph_height]u8;

const first_ascii = 32;
const last_ascii = 126;

/// Cyrillic sits at U+0410..U+044F, with Ё and ё apart from the rest.
const first_cyrillic = 0x410;
const last_cyrillic = 0x44F;
const yo_upper = 0x401;
const yo_lower = 0x451;

pub fn glyph(code: u21) *const Glyph {
    if (code >= first_ascii and code <= last_ascii) return &ascii[code - first_ascii];
    if (code >= first_cyrillic and code <= last_cyrillic) return &cyrillic[code - first_cyrillic];
    if (code == yo_upper) return &yo_upper_glyph;
    if (code == yo_lower) return &yo_lower_glyph;
    return &ascii['?' - first_ascii];
}

/// Decode one UTF-8 sequence. Returns the code point and how many bytes it
/// took; invalid input is reported as one byte of nothing so a broken stream
/// cannot stall a console.
pub fn decode(bytes: []const u8) struct { code: u21, len: usize } {
    if (bytes.len == 0) return .{ .code = 0, .len = 0 };
    const first = bytes[0];
    if (first < 0x80) return .{ .code = first, .len = 1 };
    if (first & 0xE0 == 0xC0 and bytes.len >= 2) {
        return .{
            .code = (@as(u21, first & 0x1F) << 6) | (bytes[1] & 0x3F),
            .len = 2,
        };
    }
    if (first & 0xF0 == 0xE0 and bytes.len >= 3) {
        return .{
            .code = (@as(u21, first & 0x0F) << 12) |
                (@as(u21, bytes[1] & 0x3F) << 6) |
                (bytes[2] & 0x3F),
            .len = 3,
        };
    }
    return .{ .code = '?', .len = 1 };
}

